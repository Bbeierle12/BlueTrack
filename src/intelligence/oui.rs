    fn lookup_known_apple_oui() {
        assert_eq!(lookup_oui("00:11:24:AA:BB:CC"), Some("Apple"));
    }

    #[test]
    fn lookup_case_insensitive() {
        assert_eq!(lookup_oui("00:11:24:aa:bb:cc"), Some("Apple"));
    }

    #[test]
    fn lookup_samsung_oui() {
        assert_eq!(lookup_oui("00:12:47:11:22:33"), Some("Samsung Electronics"));
    }

    #[test]
    fn lookup_unknown_oui() {
        assert_eq!(lookup_oui("FF:FF:FF:AA:BB:CC"), None);
    }

    #[test]
    fn lookup_too_short() {
        assert_eq!(lookup_oui("AA:BB"), None);
    }
