/// Look up the manufacturer name for a MAC address OUI prefix.
/// `mac` is expected in the format "AA:BB:CC:DD:EE:FF" (case-insensitive).
pub fn lookup_oui(mac: &str) -> Option<&'static str> {
    if mac.len() < 8 {
        return None;
    }
    let upper = mac[..8].to_ascii_uppercase();
    OUI_TABLE
        .iter()
        .find(|(prefix, _)| *prefix == upper)
        .map(|(_, name)| *name)
}

